"""Screenshot the real HTML report, and fail if the verdict badge is illegible.

Why this file exists: the headline of the report is a verdict badge, and a badge that
renders invisibly is the one failure a passing test suite cannot catch, because only a
browser can see pixels. So this builds the report the tool actually emits, loads it in
Chromium, reads back the computed style of the badge, and fails the run if the badge has
zero size or its text colour equals its background. The screenshot is then regenerated
from the same page, so a reviewer sees exactly what CI verified.

Dev-time only. Not part of make verify.
"""

from __future__ import annotations

import json
from pathlib import Path

from playwright.sync_api import sync_playwright

from cdc_audit.config import load_policy
from cdc_audit.pipeline import run_audit
from cdc_audit.report import render_report

ROOT = Path(__file__).resolve().parents[1]
SHOTS = ROOT / "docs" / "screenshots"

_BADGE_READBACK = """() => {
  const badge = document.querySelector('.verdictbadge');
  if (!badge) return null;
  const style = getComputedStyle(badge);
  return {
    color: style.color,
    background: style.backgroundColor,
    visible: badge.offsetWidth > 0 && badge.offsetHeight > 0,
    text: badge.textContent.trim(),
  };
}"""


def main() -> None:
    SHOTS.mkdir(parents=True, exist_ok=True)
    policy = load_policy(ROOT / "policy.toml")
    html = render_report(run_audit(policy), policy)
    report_path = SHOTS / "report.html"
    report_path.write_text(html, encoding="utf-8")

    with sync_playwright() as p:
        browser = p.chromium.launch()
        page = browser.new_page(viewport={"width": 820, "height": 900})
        page.goto(report_path.as_uri())

        badge = page.evaluate(_BADGE_READBACK)
        if badge is None:
            raise SystemExit("no verdict badge found in the report")
        if not badge["visible"]:
            raise SystemExit("verdict badge has zero size")
        if badge["color"] == badge["background"]:
            same = badge["color"]
            raise SystemExit(f"verdict badge is illegible: text and background are both {same}")

        # Clip to the content: from the top to the bottom of the caption, the last
        # element. full_page stays true even with a clip, or Chromium clamps the clip to
        # the viewport and the bottom of the table is lost.
        bottom = page.evaluate(
            "() => { const c = document.querySelector('.caption');"
            " return c ? Math.ceil(c.getBoundingClientRect().bottom) : null; }"
        )
        if bottom is None:
            raise SystemExit("caption not found; report shape changed, screenshot would be wrong")
        out = SHOTS / "verdict.png"
        page.screenshot(
            path=str(out),
            full_page=True,
            clip={"x": 0, "y": 0, "width": 820, "height": bottom + 24},
        )
        browser.close()

    manifest = {
        "verdict.png": {
            "source": "report.html generated by cdc_audit.report.render_report",
            "badge_text": badge["text"],
            "badge_color": badge["color"],
            "badge_background": badge["background"],
        }
    }
    (SHOTS / "manifest.json").write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    print(f"captured verdict.png; badge is {badge['color']} on {badge['background']}")


if __name__ == "__main__":
    main()
